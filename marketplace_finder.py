"""
Рубрика "гид по выбору" для гик-товаров.

ВАЖНО: раньше эта рубрика просила модель "придумать" конкретный товар с
конкретной ценой, рейтингом и числом отзывов и подавала это как реальную
находку на маркетплейсе. Это вводит подписчиков в заблуждение: у бота нет
доступа к реальным ценам/рейтингам/отзывам, и выдуманные цифры рано или
поздно разойдутся с тем, что человек увидит на самом маркетплейсе — это
бьёт по доверию к каналу.

Вместо этого рубрика теперь даёт честный экспертный контент: на что смотреть
при выборе товара в категории, какие характеристики реально важны, в каком
диапазоне обычно находятся цены (без точных выдуманных цифр по конкретной
модели) — и призывает подписчика самому посмотреть актуальные варианты на
маркетплейсе. Это по-прежнему полезный и вовлекающий контент (люди любят
гайды "на что смотреть перед покупкой"), но без риска соврать про
несуществующий товар.
"""

import logging
import random
from typing import Optional

from config import YANDEX_API_KEY, YANDEX_FOLDER_ID, YANDEX_MODEL, GEEK_PRODUCT_TAGS, MARKETPLACES
from content_generator import _call_yandex  # переиспользуем общий вызов YandexGPT
from telegram_api import escape as tg_escape

logger = logging.getLogger(__name__)

SYSTEM_GUIDE = """Ты — редактор Telegram-канала «Игры и Гик-новости».
Пишешь короткий экспертный гайд "на что смотреть при выборе" для гик-товара.

ВАЖНОЕ ОГРАНИЧЕНИЕ: НЕ придумывай конкретную модель, конкретную цену,
конкретный рейтинг или число отзывов, как будто ты видел реальный товар
на маркетплейсе — у тебя нет доступа к реальным данным. Говори про
категорию в целом.

Правила:
• Длина: 120–200 слов.
• Первая строка — цепляющий заголовок с эмодзи по теме категории.
• Расскажи 3-4 реальных, полезных критерия выбора для этой категории товара
  (материалы, характеристики, на что часто разводят с некачественными
  товарами, что отличает хороший экземпляр от плохого).
• Можно указать ПРИМЕРНЫЙ, широкий диапазон цен в рублях для категории
  (например "от 2 000 до 8 000 ₽ в зависимости от..."), но не точную цену
  конкретного товара.
• Тон: дружелюбный эксперт, без канцелярита.
• Только эмодзи и переносы строк, без # и **.
• Заверши призывом написать в комментариях, что подписчики ищут/выбирают,
  или вопросом по теме.
• Только русский язык."""


def find_marketplace_product() -> Optional[dict]:
    """Готовит контекст (категория + маркетплейс) для гайда по выбору.
    Возвращает словарь с готовым текстом поста (уже без выдуманных фактов)."""
    marketplace = random.choice(MARKETPLACES)
    tag         = random.choice(GEEK_PRODUCT_TAGS)

    user = (
        f"Напиши гайд «на что смотреть при выборе» для категории «{tag}». "
        f"В конце вставь строку: «Смотрите актуальные варианты и цены на {marketplace} 🔍» "
        f"(это единственное упоминание конкретного маркетплейса — цену там НЕ придумывай)."
    )

    text = _call_yandex(SYSTEM_GUIDE, user, temperature=0.7)
    if not text:
        logger.error("Marketplace guide: YandexGPT не ответил")
        return None

    logger.info(f"✅ Гайд по выбору: {tag} / {marketplace}")
    return {
        "tag":         tag,
        "marketplace": marketplace,
        "text":        tg_escape(text.strip()),
    }


def format_marketplace_post(product: dict) -> str:
    # Текст уже полностью сформирован моделью по SYSTEM_GUIDE — дополнительно
    # оборачивать в шаблон с фейковыми цифрами не нужно.
    return product.get("text", "")
